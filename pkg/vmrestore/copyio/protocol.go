// Package copyio implements bounded file scanning and zero-scan VM disk copy.
// It performs no Kubernetes, Ceph administration or guest commands.
package copyio

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
)

const (
	// Protocol is fixed in the copy image and result verifier.
	Protocol = 1
	// ChunkBytes is the scan/write quantum, not a disk-size or physical allocation claim.
	ChunkBytes = 4 << 20
	// MaxPlanBytes bounds a backend-generated plan loaded from a ConfigMap.
	MaxPlanBytes = 256 << 10
	// MaxReportBytes bounds persisted/streamed typed results independently of termination logs.
	MaxReportBytes = 256 << 10
)

var (
	// ErrInvalidPlan prevents paths, arbitrary commands and unbounded writes from input.
	ErrInvalidPlan = errors.New("copy_plan_invalid")
	// ErrIdentity prevents a changed, linked or non-regular input from being used.
	ErrIdentity = errors.New("copy_file_identity_changed")
	// ErrWriteBudget stops before a syscall can exceed granted completed bytes.
	ErrWriteBudget = errors.New("copy_write_budget_exceeded")
	// ErrDigest reports full-file or source-before/after mismatch without guest content.
	ErrDigest = errors.New("copy_full_digest_mismatch")
	id        = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$`)
	uid       = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$`)
	digest    = regexp.MustCompile(`^[a-f0-9]{64}$`)
)

// DiskPlan contains trusted resource identity and explicit read/write bounds.
type DiskPlan struct {
	VolumeID               uint   `json:"volume_id"`
	SourcePVCUID           string `json:"source_pvc_uid"`
	PreviousPVCUID         string `json:"previous_pvc_uid"`
	TargetPVCUID           string `json:"target_pvc_uid"`
	SourceMaxBytes         int64  `json:"source_max_bytes"`
	PreviousMaxBytes       int64  `json:"previous_max_bytes"`
	ExpectedSourceBytes    int64  `json:"expected_source_bytes,omitempty"`
	ExpectedSourceSHA256   string `json:"expected_source_sha256,omitempty"`
	ExpectedPreviousBytes  int64  `json:"expected_previous_bytes,omitempty"`
	ExpectedPreviousSHA256 string `json:"expected_previous_sha256,omitempty"`
	WriteLimitBytes        int64  `json:"write_limit_bytes,omitempty"`
}

// Plan is generated by the Region backend; directories derive only from index.
type Plan struct {
	ManifestHash    string     `json:"manifest_hash"`
	FrameHash       string     `json:"frame_hash"`
	Protocol        int        `json:"protocol"`
	OperationID     string     `json:"operation_id"`
	PlanHash        string     `json:"plan_hash"`
	Mode            string     `json:"mode"`
	DeadlineSeconds int64      `json:"deadline_seconds"`
	TargetUID       uint32     `json:"target_uid"`
	TargetGID       uint32     `json:"target_gid"`
	Disks           []DiskPlan `json:"disks"`
}

// FileResult records only metadata and hashes, never guest bytes.
type FileResult struct {
	UID                    uint32 `json:"uid"`
	GID                    uint32 `json:"gid"`
	Mode                   uint32 `json:"mode"`
	LogicalBytes           int64  `json:"logical_bytes"`
	ReadBytes              int64  `json:"read_bytes"`
	SHA256                 string `json:"sha256"`
	HeadSHA256             string `json:"head_sha256"`
	TailSHA256             string `json:"tail_sha256"`
	NonzeroChunkBytes      int64  `json:"nonzero_chunk_bytes"`
	ReportedStatBlocks     int64  `json:"reported_stat_blocks"`
	StatBlocksIsAllocation bool   `json:"stat_blocks_is_allocation"`
}

// DiskResult remains available on failure as far as each stage has completed.
type DiskResult struct {
	VolumeID         uint       `json:"volume_id"`
	SourcePVCUID     string     `json:"source_pvc_uid"`
	PreviousPVCUID   string     `json:"previous_pvc_uid"`
	TargetPVCUID     string     `json:"target_pvc_uid"`
	Source           FileResult `json:"source"`
	PreviousBefore   FileResult `json:"previous_before"`
	PreviousAfter    FileResult `json:"previous_after"`
	Target           FileResult `json:"target"`
	WrittenBytes     int64      `json:"written_bytes"`
	SkippedZeroBytes int64      `json:"skipped_zero_bytes"`
	Published        bool       `json:"published"`
}

// Report is persisted before any cross-stage assertion determines final success.
type Report struct {
	Protocol    int          `json:"protocol"`
	OperationID string       `json:"operation_id"`
	PlanHash    string       `json:"plan_hash"`
	Mode        string       `json:"mode"`
	OK          bool         `json:"ok"`
	Phase       string       `json:"phase"`
	ErrorCode   string       `json:"error_code,omitempty"`
	Errno       int          `json:"errno,omitempty"`
	Disks       []DiskResult `json:"disks"`
}

// Summary fits into Kubernetes' termination-message budget even for many disks.
type Summary struct {
	Protocol     int    `json:"protocol"`
	OperationID  string `json:"operation_id"`
	PlanHash     string `json:"plan_hash"`
	OK           bool   `json:"ok"`
	ReportSHA256 string `json:"report_sha256"`
	ReportBytes  int    `json:"report_bytes"`
	DiskCount    int    `json:"disk_count"`
	ErrorCode    string `json:"error_code,omitempty"`
}

// Validate enforces bounds and rejects copy mode without a fixed inspect result.
func (p Plan) Validate() error {
	expected, hashErr := PlanDigest(p)
	if hashErr != nil || p.PlanHash != expected || !digest.MatchString(p.ManifestHash) || !digest.MatchString(p.FrameHash) || p.Protocol != Protocol || !id.MatchString(p.OperationID) || !digest.MatchString(p.PlanHash) || (p.Mode != "inspect" && p.Mode != "copy" && p.Mode != "verify") || p.DeadlineSeconds < 1 || p.DeadlineSeconds > 86400 || len(p.Disks) == 0 || len(p.Disks) > 128 {
		return ErrInvalidPlan
	}
	seen := map[uint]bool{}
	for _, disk := range p.Disks {
		if disk.VolumeID == 0 || seen[disk.VolumeID] || !uid.MatchString(disk.SourcePVCUID) || !uid.MatchString(disk.PreviousPVCUID) || disk.SourceMaxBytes < 1 || disk.PreviousMaxBytes < 1 {
			return ErrInvalidPlan
		}
		seen[disk.VolumeID] = true
		if (p.Mode == "copy" || p.Mode == "verify") && (!uid.MatchString(disk.TargetPVCUID) || disk.ExpectedSourceBytes < 1 || disk.ExpectedSourceBytes > disk.SourceMaxBytes || !digest.MatchString(disk.ExpectedSourceSHA256) || disk.ExpectedPreviousBytes < 1 || disk.ExpectedPreviousBytes > disk.PreviousMaxBytes || !digest.MatchString(disk.ExpectedPreviousSHA256) || disk.WriteLimitBytes < 0 || disk.WriteLimitBytes > disk.ExpectedSourceBytes) {
			return ErrInvalidPlan
		}
	}
	return nil
}

// Directories are fixed trusted mount roots; a user cannot provide a filesystem path.
func Directories(base string, index int) (string, string, string) {
	return fmt.Sprintf("%s/input/%d", base, index), fmt.Sprintf("%s/previous/%d", base, index), fmt.Sprintf("%s/target/%d", base, index)
}

// PlanDigest is shared by backend generation and the worker, preventing partial plan substitution.
func PlanDigest(plan Plan) (string, error) {
	plan.PlanHash = ""
	data, err := json.Marshal(plan)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:]), nil
}

// SealPlan stamps the exact immutable input plan used by the Job.
func SealPlan(plan Plan) (Plan, error) {
	hash, err := PlanDigest(plan)
	plan.PlanHash = hash
	return plan, err
}
